import {readFile,writeFile,mkdir,rm,copyFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {build} from 'esbuild';
const root=new URL('../',import.meta.url),dist=new URL('dist/',root),assets=new URL('assets/',dist);
const hash=bytes=>createHash('sha256').update(bytes).digest('hex').slice(0,12);
const catalog=JSON.parse(await readFile(new URL('data/catalog.json',root)));
if(catalog.mobs.length!==179 || catalog.petals.length!==575)throw new Error('Catalog does not match the audited snapshot. Run npm run assets after reviewing an update.');
await rm(dist,{recursive:true,force:true});await mkdir(assets,{recursive:true});
const put=async(name,ext,bytes)=>{const path=`/assets/${name}.${hash(bytes)}.${ext}`;await writeFile(new URL(`.${path}`,dist),bytes);return path};
const font=await put('font','ttf',await readFile(new URL('public/assets/fredoka-one.ttf',root)));
catalog.rendering.mobAtlas=await put('mobs','png',await readFile(new URL('public/assets/mob-atlas.png',root)));
catalog.rendering.petalAtlas=await put('petals','png',await readFile(new URL('public/assets/petal-atlas.png',root)));
const data=await put('catalog','json',JSON.stringify(catalog));
const bundled=await build({entryPoints:[new URL('src/app.js',root).pathname],bundle:true,write:false,minify:true,format:'esm',target:['es2022'],define:{__CATALOG_URL__:JSON.stringify(data)}});
const app=await put('app','js',bundled.outputFiles[0].contents);
const css=await put('style','css',(await readFile(new URL('src/style.css',root),'utf8')).replace('__FONT_URL__',font));
const html=(await readFile(new URL('src/index.html',root),'utf8')).replace('__STYLE_URL__',css).replace('__APP_URL__',app);
await writeFile(new URL('index.html',dist),html);
for(const file of ['favicon.svg','sw.js','_headers','_routes.json'])await copyFile(new URL(`public/${file}`,root),new URL(file,dist));
await mkdir(new URL('licenses/',dist),{recursive:true});
await copyFile(new URL('public/licenses/Fredoka-One-OFL.txt',root),new URL('licenses/Fredoka-One-OFL.txt',dist));
console.log(`Built ${catalog.mobs.length} mobs / ${catalog.petals.length} petals → dist/`);
